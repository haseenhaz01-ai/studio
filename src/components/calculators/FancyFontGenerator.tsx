const convertText = (text: string, map: Record<string, string>): string => {
  return text.split('').map(char => map[char] || char).join('');
};

export default function FancyFontGenerator() {
  const { toast } = useToast();

  const form = useForm<FancyFontFormValues>({
    resolver: zodResolver(fancyFontGeneratorSchema),
    defaultValues: {
      text: 'Hello World',
    },
  });

  const inputText = form.watch('text');

  const copyToClipboard = (text: string) => {
    navigator.clipboard.writeText(text);
    toast({
      title: 'Copied to Clipboard!',
      description: 'The fancy text has been copied.',
    });
  };

  return (
    <Card className="mx-auto max-w-2xl">
      <CardHeader>
        <CardTitle className="font-headline">Fancy Font Generator</CardTitle>
        <CardDescription>
          Convert your text into stylish fonts you can copy and paste.
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-6">
        <Form {...form}>
          <form>
            <FormField
              control={form.control}
              name="text"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Your Text</FormLabel>
                  <FormControl>
                    <Textarea
                      placeholder="Type here..."
                      className="min-h-[100px] text-lg"
                      {...field}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />
          </form>
        </Form>
        
        {inputText && (
          <ScrollArea className="h-80 w-full rounded-md border p-4">
            <div className="space-y-4">
              {FONT_STYLES.map((style) => {
                const converted = convertText(inputText, style.map as Record<string, string>);
                return (
                  <div key={style.name} className="flex items-center justify-between gap-4 rounded-md bg-muted p-3">
                    <div>
                      <p className="text-sm font-medium text-muted-foreground">{style.name}</p>
                      <p className="text-xl">{converted}</p>
                    </div>
                    <Button variant="ghost" size="icon" onClick={() => copyToClipboard(converted)}>
                      <Copy className="h-5 w-5" />
                    </Button>
                  </div>
                );
              })}
            </div>
          </ScrollArea>
        )}
      </CardContent>
    </Card>
  );
}
